-- Usuarios de la aplicacion y tokens de refresco para el login.
-- Ejecutar una vez como el usuario PATO.

CREATE SEQUENCE SEQ_USUARIOS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE USUARIOS (
  ID_USUARIO       NUMBER        PRIMARY KEY,
  EMAIL            VARCHAR2(255) NOT NULL,
  PASSWORD_HASH    VARCHAR2(100) NOT NULL,
  ROL              VARCHAR2(20)  NOT NULL CHECK (ROL IN ('ADMIN', 'ARRENDATARIO')),
  ID_ARRENDATARIO  NUMBER        REFERENCES ARRENDATARIOS (ID_ARRENDATARIO),
  ACTIVO           NUMBER(1)     DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0, 1)),
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

-- Email unico sin importar mayusculas
CREATE UNIQUE INDEX UX_USUARIOS_EMAIL ON USUARIOS (LOWER(EMAIL));

CREATE SEQUENCE SEQ_REFRESH_TOKENS START WITH 1 INCREMENT BY 1 NOCACHE;

-- Solo se guarda el hash SHA-256 del token, nunca el token en claro
CREATE TABLE REFRESH_TOKENS (
  ID_REFRESH_TOKEN NUMBER       PRIMARY KEY,
  ID_USUARIO       NUMBER       NOT NULL REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE,
  TOKEN_HASH       VARCHAR2(64) NOT NULL UNIQUE,
  EXPIRA           TIMESTAMP    NOT NULL,
  REVOCADO         NUMBER(1)    DEFAULT 0 NOT NULL CHECK (REVOCADO IN (0, 1)),
  FECHA_CREACION   TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_REFRESH_TOKENS_USUARIO ON REFRESH_TOKENS (ID_USUARIO);
