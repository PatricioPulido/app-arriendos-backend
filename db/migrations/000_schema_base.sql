-- Esquema base de la app (Oracle), reconstruido desde los mappers de MyBatis.
-- Solo para bases NUEVAS (por ejemplo el Oracle de docker-compose o una BD en la nube).
-- Si tu BD local ya tiene estas tablas, NO lo ejecutes: sigue con 001 y 002.
-- Orden: 000 -> 001 -> 002, conectado como el usuario de la app (PATO).

CREATE SEQUENCE SEQ_CIUDAD START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE CIUDAD (
  ID_CIUDAD NUMBER        PRIMARY KEY,
  NOMBRE    VARCHAR2(100) NOT NULL
);

CREATE SEQUENCE SEQ_ZONA START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE ZONA (
  ID_ZONA   NUMBER        PRIMARY KEY,
  NOMBRE    VARCHAR2(100) NOT NULL,
  ID_CIUDAD NUMBER        NOT NULL REFERENCES CIUDAD (ID_CIUDAD)
);

CREATE SEQUENCE SEQ_DEPARTAMENTOS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE DEPARTAMENTOS (
  ID_DEPARTAMENTO  NUMBER        PRIMARY KEY,
  NOMBRE           VARCHAR2(150) NOT NULL,
  NUMERO           NUMBER(6),
  DIRECCION        VARCHAR2(255),
  METROS_CUADRADOS NUMBER(8,2),
  TIPOLOGIA        VARCHAR2(50)
);

CREATE SEQUENCE SEQ_ARRENDATARIOS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE ARRENDATARIOS (
  ID_ARRENDATARIO  NUMBER        PRIMARY KEY,
  NOMBRE           VARCHAR2(100) NOT NULL,
  APELLIDO         VARCHAR2(100) NOT NULL,
  EMAIL            VARCHAR2(255),
  TELEFONO         VARCHAR2(30),
  FECHA_NACIMIENTO DATE,
  ID_DEPARTAMENTO  NUMBER        REFERENCES DEPARTAMENTOS (ID_DEPARTAMENTO)
);

CREATE SEQUENCE SEQ_RESERVAS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE RESERVAS (
  ID_RESERVA      NUMBER       PRIMARY KEY,
  ID_DEPARTAMENTO NUMBER       NOT NULL REFERENCES DEPARTAMENTOS (ID_DEPARTAMENTO),
  ID_ARRENDATARIO NUMBER       NOT NULL REFERENCES ARRENDATARIOS (ID_ARRENDATARIO),
  FECHA_INICIO    DATE         NOT NULL,
  FECHA_FIN       DATE         NOT NULL,
  ESTADO          VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL
                  CHECK (ESTADO IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'FINALIZADA')),
  CHECK (FECHA_FIN > FECHA_INICIO)
);
CREATE INDEX IX_RESERVAS_DEPTO ON RESERVAS (ID_DEPARTAMENTO, FECHA_INICIO);
CREATE INDEX IX_RESERVAS_ARRENDATARIO ON RESERVAS (ID_ARRENDATARIO);
